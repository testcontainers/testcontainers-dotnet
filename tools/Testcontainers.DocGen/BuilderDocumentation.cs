namespace Testcontainers.DocGen;

internal sealed class BuilderDocumentation
{
    // Do not refer to a specific image. Builders that check the version treat
    // the latest tag as the newest version. If a builder requires a known
    // image, such as the Kafka vendor, the tool falls back to the constructor
    // configuration.
    private const string Image = "repository:latest";

    // ContainerBuilder.WithStartupScript copies the script to this path and
    // runs it as the main process of the container.
    private const string StartupScriptFilePath = "/testcontainers.sh";

    private const string Port = "Port";

    private const string EnvironmentVariable = "Environment variable";

    private const int MaxFileContentLength = 1024;

    // Keep characters, such as apostrophes or non-ASCII characters, readable
    // in the documented values.
    private static readonly JsonSerializerOptions JsonOptions = new JsonSerializerOptions { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    private readonly HashSet<MemberInfo> _membersWithoutSummary = new HashSet<MemberInfo>();

    private readonly Type _builderType;

    private readonly string _builderSource;

    public BuilderDocumentation(Type builderType, string builderSource)
    {
        _builderType = builderType;
        _builderSource = builderSource;
    }

    public XDocument Create()
    {
        var builder = Activator.CreateInstance(_builderType, Image);
        var settings = GetSettings(builder, fallback: true);
        var defaultSettings = settings.Except(GetSettings(new ContainerBuilder(Image)));
        var setters = GetSetters(builder, settings).ToList();

        var constructor = CreateMember("ctor", "The builder applies the following default configuration:", defaultSettings.Select(setting =>
        {
            var setter = setters.FirstOrDefault(candidate => candidate.Settings.Any(changedSetting => changedSetting.Kind == setting.Kind && changedSetting.Name == setting.Name));
            var crefs = new[] { GetPortConstantCref(setting), setter == null ? null : GetMethodCref(setter.Method) };
            return CreateItem(setting.Kind, setting.Description, crefs.Where(cref => cref != null));
        }));

        var methods = setters.Select(setter => CreateMember(GetMemberName(setter.Method), "The method applies the following configuration:", setter.Settings.Select(setting =>
        {
            var parameterName = setting.Value.Trim('{', '}');
            return CreateItem(setting.Kind, Code(setting.Name + "=") + new XElement("paramref", new XAttribute("name", parameterName)), Enumerable.Empty<string>());
        })));

        return new XDocument(
            new XComment(" Generated by tools/Testcontainers.DocGen. Do not edit this file manually. "),
            new XElement("doc", methods.Prepend(constructor)));
    }

    private IEnumerable<Setter> GetSetters(object builder, IReadOnlyCollection<Setting> settings)
    {
        var methods = _builderType.GetMethods(BindingFlags.Instance | BindingFlags.Public | BindingFlags.DeclaredOnly)
            .Where(method => method.Name.StartsWith("With") && method.ReturnType == _builderType && !method.IsDefined(typeof(ObsoleteAttribute)))
            .Where(method => method.GetParameters() is { Length: > 0 } parameters && parameters.All(parameter => parameter.ParameterType == typeof(string) && !parameter.IsOptional));

        foreach (var method in methods)
        {
            var placeholders = method.GetParameters().Select(parameter => "{" + parameter.Name + "}").ToArray();

            List<Setting> changedSettings;

            try
            {
                changedSettings = GetSettings(method.Invoke(builder, placeholders)).Except(settings).ToList();
            }
            catch (Exception e) when (e is TargetInvocationException or ArgumentException or InvalidOperationException or IOException)
            {
                // The method or the builder rejects the placeholder, such as a
                // file path that does not exist.
                continue;
            }

            // Document only methods that pass their arguments to environment
            // variables. Other methods require a hand-written description.
            if (changedSettings.Count > 0 && changedSettings.All(setting => EnvironmentVariable.Equals(setting.Kind) && placeholders.Contains(setting.Value)))
            {
                yield return new Setter(method, changedSettings);
            }
        }
    }

    private List<Setting> GetSettings(object builder, bool fallback = false)
    {
        // Accept the license agreement, so that modules which require it
        // pass the validation, and exclude it from the documentation.
        var licenseEnvVar = (string)builder.AsDynamic().AcceptLicenseAgreementEnvVar;
        object licensedBuilder = licenseEnvVar == null ? builder : ((dynamic)builder).WithEnvironment(licenseEnvVar, (string)builder.AsDynamic().AcceptLicenseAgreement);
        return GetSettings(GetConfiguration(licensedBuilder, fallback)).Where(setting => !(EnvironmentVariable.Equals(setting.Kind) && setting.Name == licenseEnvVar)).ToList();
    }

    private static IContainerConfiguration GetConfiguration(object builder, bool fallback)
    {
        try
        {
            // Build the container without starting it to include the
            // configuration that the builder applies in Build().
            IContainer container = ((dynamic)builder).Build();
            return container.AsDynamic()._configuration;
        }
        catch (Exception e) when (fallback && e is ArgumentException or InvalidOperationException)
        {
            // The builder requires a configuration that has no default value,
            // such as the Event Hubs service configuration or the Kafka vendor.
            Console.Error.WriteLine($"{builder.GetType().Name}: Failed to build the container, the documentation contains only the constructor configuration. {e.Message}");
            return builder.AsDynamic().DockerResourceConfiguration;
        }
    }

    private IEnumerable<Setting> GetSettings(IContainerConfiguration configuration)
    {
        foreach (var portBinding in OrEmpty(configuration.PortBindings))
        {
            yield return new Setting(Port, Code(portBinding.Key), portBinding.Key);
        }

        foreach (var environment in OrEmpty(configuration.Environments))
        {
            yield return new Setting(EnvironmentVariable, Code(environment.Key + "=" + environment.Value), environment.Key, environment.Value);
        }

        // The startup script overrides the entrypoint and the command. They
        // only wait for the script, so describe the script instead.
        if (OrEmpty(configuration.Command).Any(argument => argument.Contains(StartupScriptFilePath)))
        {
            yield return new Setting("Startup script", "Generates a script when the container starts and runs it as the main process.");
        }
        else
        {
            if (OrEmpty(configuration.Entrypoint).Any())
            {
                yield return new Setting("Entrypoint", Code(string.Join(" ", configuration.Entrypoint)));
            }

            if (OrEmpty(configuration.Command).Any())
            {
                yield return new Setting("Command", Code(string.Join(" ", configuration.Command)));
            }
        }

        foreach (var resourceMapping in OrEmpty(configuration.ResourceMappings))
        {
            // Include the content of short text files only, such as
            // configuration files.
            var bytes = resourceMapping.GetAllBytesAsync().GetAwaiter().GetResult();
            var content = bytes.Length <= MaxFileContentLength && !bytes.Contains((byte)0) ? new XElement("code", Encoding.UTF8.GetString(bytes).TrimEnd()).ToString(SaveOptions.DisableFormatting) : string.Empty;
            yield return new Setting("File", Code(resourceMapping.Target) + content);
        }

        foreach (var mount in OrEmpty(configuration.Mounts))
        {
            yield return new Setting("Mount", Code(mount.Target));
        }

        if (configuration.Privileged == true)
        {
            yield return new Setting("Privileged", Code(bool.TrueString.ToLowerInvariant()));
        }

        foreach (var createParameter in GetCreateParameters(configuration.ParameterModifiers))
        {
            yield return new Setting("Create parameter", Code(createParameter));
        }

        foreach (var container in OrEmpty(configuration.Containers))
        {
            yield return new Setting("Dependency", Code(container.Image.FullName));
        }

        foreach (var waitStrategy in OrEmpty(configuration.WaitStrategies))
        {
            yield return new Setting("Wait strategy", GetWaitStrategyDescription(waitStrategy));
        }

        if (GetStartupCallback(configuration.StartupCallback) is { } startupCallback)
        {
            yield return new Setting("Startup callback", GetSummary(startupCallback, "Runs a callback specific to the module after the container starts."));
        }
    }

    private static IEnumerable<string> GetCreateParameters(IEnumerable<Action<CreateContainerParameters>> parameterModifiers)
    {
        // Apply the modifiers to parameters with the nested objects that the
        // container creates as well, and document the values that they change.
        var parameters = new CreateContainerParameters { HostConfig = new HostConfig(), NetworkingConfig = new NetworkingConfig() };
        var defaultParameters = Flatten(JsonSerializer.SerializeToNode(parameters), null).ToList();

        foreach (var parameterModifier in OrEmpty(parameterModifiers))
        {
            parameterModifier(parameters);
        }

        return Flatten(JsonSerializer.SerializeToNode(parameters), null).Except(defaultParameters);
    }

    private static IEnumerable<string> Flatten(JsonNode node, string path)
    {
        return node switch
        {
            null => Enumerable.Empty<string>(),
            JsonObject jsonObject => jsonObject.SelectMany(property => Flatten(property.Value, path == null ? property.Key : path + "." + property.Key)),
            _ => new[] { path + "=" + node.ToJsonString(JsonOptions) },
        };
    }

    private string GetWaitStrategyDescription(WaitStrategy waitStrategy)
    {
        IWaitUntil waitUntil = waitStrategy.AsDynamic()._waitUntil;
        IWaitWhile waitWhile = waitStrategy.AsDynamic()._waitWhile;

        var condition = (object)waitUntil ?? waitWhile;

        if (condition == null)
        {
            return Code(nameof(WaitStrategy));
        }

        var conditionType = condition.GetType();

        // Describe module wait strategies with the summary of their
        // declaration. Their state is internal to the module.
        if (conditionType.Assembly != typeof(WaitStrategy).Assembly)
        {
            return GetSummary(conditionType, "Waits until a condition specific to the module is met.");
        }

        var state = condition.AsDynamic();

        return conditionType.Name switch
        {
            "UntilMessageIsLogged" => "Waits until a message matching " + Code(((Regex)state._pattern).ToString()) + " is logged.",
            "UntilUnixCommandIsCompleted" => "Waits until the command " + Code(string.Join(" ", (string[])state._command)) + " is completed successfully.",
            "UntilContainerIsHealthy" => "Waits until the container is healthy.",
            "UntilExternalTcpPortIsAvailable" => "Waits until the TCP port " + Code(((int)state._containerPort).ToString()) + " is available from the test host to the container.",
            "UntilInternalTcpPortIsAvailableOnUnix" => "Waits until a TCP port is available from within the container itself.",
            nameof(HttpWaitStrategy) => "Waits until the " + ((string)state._schemeName).ToUpperInvariant() + " request " + Code(((HttpMethod)state._httpMethod).Method + " " + (string)state._pathValue) + ((ushort?)state._portNumber is { } port ? " to port " + Code(port.ToString()) : string.Empty) + " is completed successfully.",
            _ => Code(conditionType.Name),
        };
    }

    private static MethodInfo GetStartupCallback(Delegate startupCallback)
    {
        if (startupCallback == null)
        {
            return null;
        }

        var method = startupCallback.Method;

        if (method.DeclaringType.Assembly != typeof(ContainerBuilder).Assembly && !method.Name.Contains('<'))
        {
            return method;
        }

        // The builder wraps the module callback in a closure. Search the
        // captured delegates for the module method.
        return startupCallback.Target?.GetType().GetFields(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic)
            .Select(field => field.GetValue(startupCallback.Target))
            .OfType<Delegate>()
            .Select(GetStartupCallback)
            .FirstOrDefault(callback => callback != null);
    }

    private string GetSummary(MemberInfo member, string fallback)
    {
        // The XML documentation file contains only public members. Read the
        // summary of a private member from the builder source instead. The
        // declaration must follow the documentation, not a line within it.
        var declarationPattern = member is Type ? "class " + Regex.Escape(member.Name) + @"\b" : Regex.Escape(member.Name) + @"\(";
        var match = Regex.Match(_builderSource, @"(?<doc>(?:^[ \t]*///.*\n)+)(?![ \t]*///)[^\n]*\b" + declarationPattern, RegexOptions.Multiline);

        XElement summary = null;

        if (match.Success)
        {
            var doc = Regex.Replace(match.Groups["doc"].Value, @"^[ \t]*/// ?", string.Empty, RegexOptions.Multiline);
            summary = XElement.Parse("<doc>" + doc + "</doc>").Element("summary");
        }

        if (summary == null)
        {
            if (_membersWithoutSummary.Add(member))
            {
                Console.Error.WriteLine($"{_builderType.Name}: Failed to find the summary of '{member.Name}' in the builder source, the documentation contains a generic description. Add a summary to its declaration.");
            }

            return fallback;
        }

        // References do not resolve in the documentation that includes the
        // summary. Replace them with their names.
        foreach (var reference in summary.Descendants().Where(element => element.Attribute("cref") != null || element.Name.LocalName is "paramref" or "typeparamref").ToList())
        {
            reference.ReplaceWith(new XElement("c", (string)reference.Attribute("cref") ?? (string)reference.Attribute("name")));
        }

        return Regex.Replace(string.Concat(summary.Nodes()), @"\s+", " ").Trim();
    }

    private string GetPortConstantCref(Setting setting)
    {
        if (!Port.Equals(setting.Kind))
        {
            return null;
        }

        // Link the public constant with the same port, which users pass to
        // GetMappedPublicPort. Values of environment variables, such as 1,
        // match unrelated constants too, so do not link them.
        var constants = _builderType.GetFields(BindingFlags.Public | BindingFlags.Static)
            .Where(field => field.IsLiteral && field.FieldType != typeof(string) && !field.IsDefined(typeof(ObsoleteAttribute)))
            .Where(field => setting.Name.Equals(Convert.ToString(field.GetRawConstantValue(), CultureInfo.InvariantCulture)))
            .ToList();

        return constants.Count == 1 ? "F:" + _builderType.FullName + "." + constants[0].Name : null;
    }

    private string GetMethodCref(MethodInfo method)
    {
        return "M:" + _builderType.FullName + "." + GetMemberName(method);
    }

    private static string GetMemberName(MethodInfo method)
    {
        return method.Name + "(" + string.Join(",", method.GetParameters().Select(parameter => parameter.ParameterType.FullName)) + ")";
    }

    private static XElement CreateMember(string name, string description, IEnumerable<XElement> items)
    {
        return new XElement("member", new XAttribute("name", name), new XElement("para", description), new XElement("list", new XAttribute("type", "bullet"), items));
    }

    private static XElement CreateItem(string kind, string description, IEnumerable<string> crefs)
    {
        var references = string.Join(", ", crefs.Select(cref => new XElement("see", new XAttribute("cref", cref))));

        // Start the description with text, so that the writer does not indent
        // the inline elements and add whitespace between them.
        return new XElement("item", XElement.Parse("<description>" + kind + ": " + description + (references.Length == 0 ? string.Empty : " (see " + references + ")") + "</description>"));
    }

    private static string Code(string text)
    {
        return new XElement("c", text).ToString(SaveOptions.DisableFormatting);
    }

    private static IEnumerable<T> OrEmpty<T>(IEnumerable<T> items)
    {
        return items ?? Enumerable.Empty<T>();
    }

    private sealed record Setter(MethodInfo Method, IReadOnlyCollection<Setting> Settings);

    // The description is an XML fragment. The name and the value identify
    // ports and environment variables.
    private sealed record Setting(string Kind, string Description, string Name = null, string Value = null);
}