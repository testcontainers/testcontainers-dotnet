namespace Testcontainers.DocGen;

internal static class MarkdownDocumentation
{
    // Python-Markdown supports backslash escapes for these characters, but
    // not for '<'. The tool replaces it with an entity instead.
    private static readonly Regex SpecialCharacterPattern = new Regex(@"[\\`*_\[\]]", RegexOptions.None, TimeSpan.FromSeconds(1));

    private static readonly Regex BacktickPattern = new Regex("`+", RegexOptions.None, TimeSpan.FromSeconds(1));

    private static readonly Dictionary<string, string> TypeAliases = new Dictionary<string, string>
    {
        { typeof(bool).FullName, "bool" },
        { typeof(int).FullName, "int" },
        { typeof(long).FullName, "long" },
        { typeof(string).FullName, "string" },
    };

    public static string Create(XDocument document)
    {
        // Render the default configuration only. Its items already reference
        // the builder methods that change the configuration.
        var member = document.XPathSelectElement("doc/member[@name='ctor']");

        var blocks = member.Elements().Select(element => element.Name.LocalName switch
        {
            "para" => GetText(element),
            "list" => string.Join(Environment.NewLine, element.Elements("item").Select(item => GetListItem(item.Element("description")))).TrimEnd(),
            _ => throw new InvalidOperationException($"The element '{element.Name}' is not supported."),
        });

        var comment = "<!-- Generated by tools/Testcontainers.DocGen. Do not edit this file manually. -->";
        return string.Join(Environment.NewLine + Environment.NewLine, blocks.Prepend(comment)) + Environment.NewLine;
    }

    private static string GetListItem(XElement description)
    {
        var listItem = new StringBuilder("- " + GetText(description));

        // Indent the code blocks, so that they belong to the list item, and
        // end them with a blank line, so that the next list item does not
        // continue them.
        foreach (var code in description.Elements("code"))
        {
            listItem.AppendLine();
            listItem.AppendLine();
            listItem.AppendLine(string.Join(Environment.NewLine, GetCodeBlock(code.Value).Select(line => line.Length == 0 ? line : "    " + line)));
        }

        return listItem.ToString();
    }

    private static string GetText(XElement element)
    {
        // Skip the code blocks. The list item renders them after the text.
        return string.Concat(element.Nodes().Select(node => node switch
        {
            XText text => SpecialCharacterPattern.Replace(text.Value, @"\$0").Replace("<", "&lt;"),
            XElement { Name.LocalName: "c" } code => GetCodeSpan(code.Value),
            XElement { Name.LocalName: "see" } see => GetCodeSpan(GetName((string)see.Attribute("cref"))),
            XElement { Name.LocalName: "paramref" } paramref => GetCodeSpan((string)paramref.Attribute("name")),
            XElement { Name.LocalName: "code" } => string.Empty,
            _ => throw new InvalidOperationException($"The node '{node}' is not supported."),
        }));
    }

    private static string GetName(string cref)
    {
        // Render the reference without the namespace and with C# type
        // aliases like the IDE, such as 'PostgreSqlBuilder.WithDatabase(string)'.
        var match = Regex.Match(cref, @"^[A-Z]:(?<name>[^(]+)(?:\((?<parameters>[^)]*)\))?$", RegexOptions.None, TimeSpan.FromSeconds(1));

        var name = string.Join(".", match.Groups["name"].Value.Split('.').TakeLast(2));

        if (!match.Groups["parameters"].Success)
        {
            return name;
        }

        var parameters = match.Groups["parameters"].Value.Split(',').Select(parameter => TypeAliases.TryGetValue(parameter, out var alias) ? alias : parameter.Split('.')[^1]);
        return name + "(" + string.Join(", ", parameters) + ")";
    }

    private static string GetCodeSpan(string text)
    {
        // Delimit the code with more backticks than it contains, and separate
        // a backtick at its start or end from the delimiter with a space.
        var delimiter = new string('`', GetLongestBacktickRun(text) + 1);
        var padding = text.StartsWith('`') || text.EndsWith('`') ? " " : string.Empty;
        return delimiter + padding + text + padding + delimiter;
    }

    private static IEnumerable<string> GetCodeBlock(string text)
    {
        var fence = new string('`', Math.Max(3, GetLongestBacktickRun(text) + 1));
        return text.Split('\n').Prepend(fence).Append(fence);
    }

    private static int GetLongestBacktickRun(string text)
    {
        return BacktickPattern.Matches(text).Select(match => match.Length).DefaultIfEmpty(0).Max();
    }
}